"""Feature engineering: one modelling frame per line of business (train + test share identical columns)."""
from __future__ import annotations

import numpy as np
import pandas as pd

from prep import LINES, attach_claims, load_claims, load_policies, read

# Fields judged to be identifiers or business-process noise with no causal link to claim cost.
# Kept in one place so the choice is auditable and can be ablated.
NOISE_COLS = [
    "surname", "email_domain", "marketing_consent", "document_preference", "campaign_code",
    "branch_id", "marketing_segment", "previous_insurer", "vehicle_colour",
]
ID_COLS = ["row_id", "policy_id", "customer_id", "address_id", "period_start", "period_end"]
# Columns that exist in training only, or that are generated by the claim outcome itself.
# customer_service_contacts: contacts track same-period claims in training (corr 0.75 with claim_count; zero contacts
# => ~zero claims) but the 2025 test mean is a flat 0.40 on every line, i.e. not claim-driven -> train/test leak.
LEAK_COLS = ["renewal_decision", "customer_service_contacts"]
PRICING_COLS = ["written_premium", "discount_applied"]  # current-tariff outputs: ablate, risky if the market changes
WEATHER_COLS = ["hail_days", "wind_exposure_index", "freezing_days", "dry_summer_index", "wildfire_index",
                "rainfall_mm", "mean_temperature_c"]


def _history(rows: pd.DataFrame, claims: pd.DataFrame, pol_cust: pd.DataFrame, line: str) -> pd.DataFrame:
    """Claim history known strictly before each row starts (report_date < period_start)."""
    out = pd.DataFrame(index=rows.index)
    base = rows[["policy_id", "customer_id", "period_start"]].copy()
    base["_i"] = base.index

    def agg(keys: str, cl: pd.DataFrame, prefix: str) -> pd.DataFrame:
        m = base[[keys, "period_start", "_i"]].merge(cl[[keys, "report_date", "net_capped"]], on=keys, how="inner")
        m = m[m["report_date"] < m["period_start"]]
        g = m.groupby("_i").agg(n=("net_capped", "size"), cost=("net_capped", "sum"), mx=("net_capped", "max"))
        g.columns = [f"{prefix}_n", f"{prefix}_cost", f"{prefix}_max"]
        return g.reindex(base["_i"]).fillna(0).set_index(base.index)

    cl_line = claims[claims["line"] == line]
    cap = cl_line.loc[cl_line["net_incurred"] > 0, "net_incurred"].quantile(0.999)
    cl_line = cl_line.assign(net_capped=cl_line["net_incurred"].clip(upper=cap))
    out = out.join(agg("policy_id", cl_line, "hist_pol"))

    allc = claims.assign(net_capped=claims["net_incurred"].clip(upper=claims["net_incurred"].quantile(0.999)))
    allc = allc.merge(pol_cust, on="policy_id", how="left").dropna(subset=["customer_id"])
    out = out.join(agg("customer_id", allc, "hist_cust"))
    return out


def _prior_exposure(train: pd.DataFrame, test: pd.DataFrame) -> tuple[pd.Series, pd.Series]:
    """Years of observed (train-period) exposure on the same policy before each row."""
    t = train.sort_values(["policy_id", "period_start"])
    cum = t.groupby("policy_id")["exposure"].cumsum() - t["exposure"]
    pe_train = cum.reindex(train.index)
    tot = train.groupby("policy_id")["exposure"].sum()
    pe_test = test["policy_id"].map(tot).fillna(0.0)
    return pe_train, pe_test


def build(line: str, cap_q: float = 0.999) -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    """Return (train_frame, test_frame, meta). Train frame holds targets: claim_count, net_incurred, net_capped."""
    claims = load_claims()
    train = load_policies(line)
    test = load_policies(line, test=True)
    train, _ = attach_claims(train, claims, line, cap_q)
    cap = train.attrs["cap"]

    pol_cust = pd.concat(
        [load_policies(l)[["policy_id", "customer_id"]] for l in LINES]
    ).drop_duplicates("policy_id")

    cust = read("customers")
    addr = read("addresses")
    weather = read("weather")

    def enrich(df: pd.DataFrame) -> pd.DataFrame:
        df = df.merge(cust, on="customer_id", how="left").merge(addr, on="address_id", how="left")
        df = df.merge(weather, on=["address_id", "year"], how="left")
        dob = pd.to_datetime(df["date_of_birth"])
        df["age_at_start"] = (df["period_start"] - dob).dt.days / 365.25
        df["start_doy"] = df["period_start"].dt.dayofyear
        df["end_doy"] = df["period_end"].dt.dayofyear
        df["property_age"] = df["year"] - df["year_built"]
        df["tenure_years"] = df["year"] - df["customer_since_year"]
        if "driver_age" in df and "years_licensed" in df:
            df["age_at_licence"] = df["driver_age"] - df["years_licensed"]
        return df

    train, test = enrich(train), enrich(test)
    pe_train, pe_test = _prior_exposure(train, test)
    train["prior_exposure"], test["prior_exposure"] = pe_train.values, pe_test.values

    train = train.join(_history(train, claims, pol_cust, line))
    test = test.join(_history(test, claims, pol_cust, line))
    for d in (train, test):
        d["hist_pol_freq"] = d["hist_pol_n"] / d["prior_exposure"].clip(lower=0.25)

    meta = {"cap": cap, "line": line}
    return train, test, meta


def feature_columns(df: pd.DataFrame, use_pricing: bool = False, use_weather: bool = True,
                    use_history: bool = True, use_noise: bool = False) -> list[str]:
    targets = {"claim_count", "net_incurred", "net_capped", "paid", "open_count", "year", "exposure",
               "date_of_birth", "customer_since_year", "year_built", "dev_f"}
    drop = set(ID_COLS) | set(LEAK_COLS) | targets
    if not use_noise:
        drop |= set(NOISE_COLS)
    if not use_pricing:
        drop |= set(PRICING_COLS)
    if not use_weather:
        drop |= set(WEATHER_COLS)
    cols = [c for c in df.columns if c not in drop]
    if not use_history:
        cols = [c for c in cols if not (c.startswith("hist_") or c == "prior_exposure")]
    return cols


def to_model_frame(train: pd.DataFrame, test: pd.DataFrame, cols: list[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Cast object/bool columns to pandas category with category sets shared between train and test."""
    X, Xt = train[cols].copy(), test[cols].copy()
    for c in cols:
        if X[c].dtype == object or str(X[c].dtype) in ("bool", "string"):
            cats = pd.Index(pd.concat([X[c], Xt[c]]).astype(str).unique())
            X[c] = pd.Categorical(X[c].astype(str), categories=cats)
            Xt[c] = pd.Categorical(Xt[c].astype(str), categories=cats)
    return X, Xt
